--- @param hex string
--- @param opacity number
local function alpha(hex, opacity) return hex .. string.format("%02X", math.floor(opacity * 255 + 0.5)) end

--- @param src string
--- @param dst string
--- @param amount number
local function blend(src, dst, amount) return Color.new(src):blend(Color.new(dst), amount):tohex() end

local function is_array(t)
  local i = 0
  for _ in pairs(t) do
    i = i + 1
    if t[i] == nil then return false end
  end
  return true
end

local function encode(val, indent)
  indent = indent or 0
  local ty = type(val)
  if ty == "boolean" then
    return val and "true" or "false"
  elseif ty == "number" then
    return tostring(val)
  elseif ty == "string" then
    return vim.json.encode(val)
  elseif ty == "table" then
    local pad = string.rep("  ", indent)
    local inner = string.rep("  ", indent + 1)
    if is_array(val) then
      if #val == 0 then return "[]" end
      local parts = {}
      for _, v in ipairs(val) do
        table.insert(parts, inner .. encode(v, indent + 1))
      end
      return "[\n" .. table.concat(parts, ",\n") .. "\n" .. pad .. "]"
    end
    local keys = {}
    for k in pairs(val) do
      table.insert(keys, k)
    end
    table.sort(keys)
    if #keys == 0 then return "{}" end
    local parts = {}
    for _, k in ipairs(keys) do
      table.insert(parts, inner .. vim.json.encode(k) .. ": " .. encode(val[k], indent + 1))
    end
    return "{\n" .. table.concat(parts, ",\n") .. "\n" .. pad .. "}"
  end
  error("cannot encode " .. ty)
end

local function scope(name, scopes, foreground, settings)
  local s = vim.tbl_extend("force", { foreground = foreground }, settings or {})
  return { name = name, scope = scopes, settings = s }
end

