--- @param colors AstroThemePalette
function M.generate(colors)
  local dark = Color.new(colors.ui.base):less(127)
  local theme = {
    name = colors._style_name,
    type = dark and "dark" or "light",
    semanticHighlighting = true,
    semanticTokenColors = semantic_tokens(colors),
    colors = workbench(colors),
    tokenColors = token_colors(colors),
  }
  return encode(theme) .. "\n"
end

return M
